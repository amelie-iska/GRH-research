#!/usr/bin/env python3
"""Assemble reviewed chapter material without modifying its article sources."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
P=ROOT/'papers'

def expand(text):
    return re.sub(r"\\input\{([^}]+)\}",lambda m:expand((P/(m[1]+'.tex')).read_text()),text)

def blocks(name):
    text=expand((P/name).read_text()).replace(r'\appendix','')
    return re.split(r"(?=^\\section\{)",text,flags=re.M)

def main():
    core=blocks('dessin-core.tex'); details=blocks('dessin-details.tex')
    # Each block keeps its labels, proof statements and citations byte-for-byte.
    # Source order is recorded in the generated chapter; no theorem is inferred.
    chunks=['% Generated by scripts/assemble_book.py; edit shared papers instead.\n']
    for title,source in [('Constructions and statements',core),('Proofs and calculations',details)]:
        chunks.append('\\part{'+title+'}\n')
        for block in source:
            if not block.strip(): continue
            block=re.sub(r'^\\section\{',r'\\chapter{',block,flags=re.M)
            block=re.sub(r'^\\subsection\{',r'\\section{',block,flags=re.M)
            block=re.sub(r'^\\subsubsection\{',r'\\subsection{',block,flags=re.M)
            chunks.append(block)
    out=ROOT/'book/chapters/reviewed-mathematics.tex'
    out.write_text('\n'.join(chunks))
    print(out)
if __name__=='__main__': main()
