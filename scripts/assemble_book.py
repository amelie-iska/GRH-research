#!/usr/bin/env python3
"""Assemble reviewed chapter material without modifying its article sources."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
P=ROOT/'papers'

def expand(text):
    return re.sub(r"\\input\{([^}]+)\}",lambda m:expand((P/(m[1]+'.tex')).read_text()),text)

def blocks(name):
    text=expand((P/name).read_text()).replace(r'\appendix','')
    return re.split(r"(?=^\\section\{)",text,flags=re.M)

def main():
    core=blocks('dessin-core.tex'); details=blocks('dessin-details.tex')
    # Shared labels/proofs/citations are retained; duplicate diagram renderings
    # are cross-referenced to their canonical AR chapter, not deleted from sources.
    # Source order is recorded in the generated chapter; no theorem is inferred.
    chunks=['% Generated by scripts/assemble_book.py; edit shared papers instead.\n']
    for title,source in [('Constructions and statements',core),('Proofs and calculations',details)]:
        chunks.append('\\part{'+title+'}\n')
        for block in source:
            if not block.strip(): continue
            if title=='Proofs and calculations':
                block=re.sub(r'\\\[\s*\\begin\{tikzcd\}.*?\\end\{tikzcd\}\s*\\\]',lambda m:r'\par\noindent The canonical diagram appears in Chapter~\ref{arb:chapter}; the proof and calculation below are retained.\par',block,flags=re.S)
                block=re.sub(r'\\begin\{tikzcd\}.*?\\end\{tikzcd\}',lambda m:r'\textnormal{See the canonical diagram in Chapter~\ref{arb:chapter}.}',block,flags=re.S)
            block=re.sub(r'^\\section\{',r'\\chapter{',block,flags=re.M)
            block=re.sub(r'^\\subsection\{',r'\\section{',block,flags=re.M)
            block=re.sub(r'^\\subsubsection\{',r'\\subsection{',block,flags=re.M)
            chunks.append(block)
    out=ROOT/'book/chapters/reviewed-mathematics.tex'
    out.write_text('\n'.join(chunks))
    (ROOT/'book/chapters/short-row-pair.tex').write_text('% Generated from the shared arithmetic article fragments.\n'+(P/'short-row-pair-core.tex').read_text()+'\n'+(P/'short-row-pair-details.tex').read_text().replace(r'\section{',r'\subsection{',1))
    (ROOT/'book/chapters/mobius-split.tex').write_text('% Generated from the shared signed arithmetic fragments.\n'+(P/'mobius-split-core.tex').read_text()+'\n'+(P/'mobius-split-details.tex').read_text().replace(r'\subsection{',r'\subsubsection{').replace(r'\section{',r'\subsection{',1))
    for name in ['rg-core','rg-details','relations-core','relations-details','branch-extension-core','branch-extension-details','convextok']:
        (ROOT/f'book/chapters/{name}.tex').write_text(('% Generated shared actual RG material.\n' if name in ['rg-core','rg-details','relations-core','relations-details'] else '% Generated shared reviewed material.\n')+(P/f'{name}.tex').read_text())
    print(out)
if __name__=='__main__': main()
